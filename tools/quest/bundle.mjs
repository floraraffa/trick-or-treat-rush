// npm run quest:bundle -- [out folder]
// The game's assets and data for a Meta Quest project that is not trick-or-treat-rush-quest (the team keeps its
// own): two ZIPs under <out> (default ./quest-bundle):
//   trick-or-treat-rush-quest-unity-<part>.zip   for Unity: every neighbourhood whole and textured, the flying
//                                                 cars, the ghost, the five creatures, candy and gems, the effects,
//                                                 the costumes, the sounds and music (WAV), the cries (MP3), the two
//                                                 fonts (TTF), the moves as a Humanoid FBX, and everything below
//   trick-or-treat-rush-quest-chat.zip            text only, small, for another chat to read: LEEME.md, the rules,
//                                                 plan, neighbourhoods, traffic and texts as JSON and as C#, the
//                                                 game's own sources that build them (reference), a few previews
// The models come from the Spectacles exporter (tools/lens-studio/export.mjs, headless Chromium), the moves from
// Blender (clips-fbx.mjs). Nothing here changes the game.
import { spawnSync } from 'node:child_process';
import { copyFileSync, cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildClipsFbx } from './clips-fbx.mjs';
import { rulesCs, uiCs } from './rules-cs.mjs';
import { textsCs } from './texts-cs.mjs';
import * as C from '../../src/game/config.js';
import * as L from '../../src/world/layout.js';
import { HOOD_MATERIAL, NIGHT_THEMES, THEMES } from '../../src/world/themes.js';
import { FLEET, LANES, POLICE_FLASH } from '../../src/world/traffic.js';
import { LANGS, STRINGS } from '../../src/ui/i18n.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(process.argv.slice(2).find((a) => !a.startsWith('--')) ?? join(ROOT, 'quest-bundle'));
const BASE = join(OUT, 'TrickOrTreatRush-Quest');
// (`--keep-assets`: the models, sounds, fonts and moves of a bundle made before stay; the rest is made again)
const KEEP = process.argv.includes('--keep-assets') && existsSync(join(BASE, 'Models'));
if (KEEP) for (const d of ['Data', 'CSharp', 'Reference', 'Previews', 'LEEME.md', 'CREDITS.md']) rmSync(join(BASE, d), { recursive: true, force: true });
else rmSync(BASE, { recursive: true, force: true });
const write = (rel, data) => { const f = join(BASE, rel); mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, data); };
const HEADER = (from) => `// Generated by trick-or-treat-rush/tools/quest/bundle.mjs from ${from}. Change the game and export again.\n`;
const f3 = (v) => `${Number(v).toFixed(4)}f`;

// --- data: JSON ---------------------------------------------------------------------------------------------
const json = (v) => JSON.stringify(v, (k, x) => (x === Infinity ? 'Infinity' : x), 1);
const conf = Object.fromEntries(Object.entries(C).filter(([, v]) => typeof v !== 'function'));
conf.NIGHT_RULES = C.NIGHTS.map((_, i) => C.nightRules(i));
write('Data/rules.json', json(conf));
write('Data/layout.json', json(Object.fromEntries(Object.entries(L).filter(([, v]) => typeof v !== 'function'))));
write('Data/neighbourhoods.json', json({ NIGHT_THEMES, THEMES, HOOD_MATERIAL }));
write('Data/traffic.json', json({ LANES, FLEET, POLICE_FLASH, note: 'see Reference/src/world/traffic.js vehiclePose(v, t)' }));
write('Data/texts.json', json({ LANGS, STRINGS }));
console.log('✔ data: rules, layout, neighbourhoods, traffic, texts (JSON)');

// --- data: C# -----------------------------------------------------------------------------------------------
// The rules ported to C# by hand (trick-or-treat-rush-quest, next to this repository: Authority, View, the player,
// collisions... checked line by line against this game's reference rounds there), with their generated data.
const QUEST = resolve(process.env.QUEST_REPO ?? join(ROOT, '../trick-or-treat-rush-quest'));
const rulesDir = join(QUEST, 'Assets/TrickOrTreat/Scripts/Rules');
if (existsSync(rulesDir)) {
  mkdirSync(join(BASE, 'CSharp/Rules'), { recursive: true });
  for (const f of readdirSync(rulesDir)) if (/\.(cs|asmdef)$/.test(f)) copyFileSync(join(rulesDir, f), join(BASE, 'CSharp/Rules', f));
} else console.log(`(no ${rulesDir}: only the generated data)`);
write('CSharp/Rules/Generated/RulesData.cs', rulesCs(HEADER('src/game/config.js and src/world/layout.js')));
write('CSharp/Rules/Generated/TextsData.cs', textsCs(HEADER('src/ui/i18n.js')));
write('CSharp/Rules/Generated/UiData.cs', uiCs(HEADER('src/dev/lens-ui.js')));
const col = (c) => `new Color(${f3(c[0])}, ${f3(c[1])}, ${f3(c[2])})`;
const looks = Object.values(THEMES).map((T) => `      new Look { Id = "${T.name}", SkyHorizon = ${col(T.sky.horizon)}, SkyMid = ${col(T.sky.mid)}, SkyZenith = ${col(T.sky.zenith)}, Stars = ${T.sky.stars}, Moon = "${T.sky.moon}", MoonSize = ${f3(T.sky.moonSize)}, Aurora = ${!!T.sky.aurora}, Snowfall = ${!!T.snowfall}, Traffic = ${!!T.traffic},
        FogCalm = ${col(T.fog.calm.color)}, FogCalmDensity = ${f3(T.fog.calm.density)}, MistCalm = ${col(T.fog.calm.mist)}, FogMad = ${col(T.fog.mad.color)}, FogMadDensity = ${f3(T.fog.mad.density)}, MistMad = ${col(T.fog.mad.mist)},
        AmbientCalm = ${col(T.ambient[0])}, AmbientMad = ${col(T.ambient[1])}, MoonlightCalm = ${col(T.moonLight[0])}, MoonlightMad = ${col(T.moonLight[1])}, Lamp = ${col(T.lampColor)} },`).join('\n');
write('CSharp/Look/NeighbourhoodsData.cs', `${HEADER('src/world/themes.js')}// Each night's neighbourhood and its light: the sky's colours, its moon (moon, earth, bulb), stars, fog (calm and in
// the Monster Madness: colour, exp2 density, the ground mist's colour), ambient light, moonlight, the lamps' colour.
// Its model is Models/QuestVillages/village-<Id>.glb.
using UnityEngine;
namespace TrickOrTreat.Look {
  public sealed class Look {
    public string Id, Moon; public Color SkyHorizon, SkyMid, SkyZenith; public int Stars; public float MoonSize; public bool Aurora, Snowfall, Traffic;
    public Color FogCalm, MistCalm, FogMad, MistMad, AmbientCalm, AmbientMad, MoonlightCalm, MoonlightMad, Lamp; public float FogCalmDensity, FogMadDensity;
  }
  public static class Neighbourhoods {
    /** Night n (0-based) of the campaign is played in NIGHT_THEMES[n]; the levels' rounds in "classic". */
    public static readonly string[] NIGHT_THEMES = { ${NIGHT_THEMES.map((id) => `"${id}"`).join(', ')} };
    public static readonly Look[] LOOKS = {
${looks}
    };
    public static Look Of(string id) { foreach (var l in LOOKS) if (l.Id == id) return l; return LOOKS[0]; }
    public static string OfNight(int n) => n >= 0 && n < NIGHT_THEMES.Length ? NIGHT_THEMES[n] : "classic";
  }
}
`);
write('CSharp/Look/TrafficData.cs', `${HEADER('src/world/traffic.js')}// The cyberpunk city's flying traffic (only for the look: no rule knows of it), as the web game and the Spectacles
// Lens move it: loops round the plaza at several heights (r, y in metres; speed m/s; dir ±1; wob: how much the
// radius wavers, three times round). Pose() gives Unity-space values for models imported by glTFast, which flips
// glTF's X: the game's point (x, y, z) is (-x, y, z), and its turns about Y and Z go the other way.
// The cars are Models/QuestVillages/vehicles.glb: vehicle-car-0/1/2, vehicle-taxi, vehicle-police (with its
// police-red and police-blue lights to switch on in turn).
using UnityEngine;
namespace TrickOrTreat.Look {
  public static class Traffic {
    public struct Lane { public float R, Y, Speed, Dir, Wob; public Lane(float r, float y, float speed, float dir, float wob) { R = r; Y = y; Speed = speed; Dir = dir; Wob = wob; } }
    public struct Car { public string Kind; public int Paint, Lane; public float At; public Car(string kind, int paint, int lane, float at) { Kind = kind; Paint = paint; Lane = lane; At = at; } public string Model => Kind == "car" ? "vehicle-car-" + Paint : "vehicle-" + Kind; }
    public static readonly Lane[] LANES = {
${LANES.map((l) => `      new Lane(${f3(l.r)}, ${f3(l.y)}, ${f3(l.speed)}, ${f3(l.dir)}, ${f3(l.wob)}),`).join('\n')}
    };
    public static readonly Car[] FLEET = {
${FLEET.map((v) => `      new Car("${v.kind}", ${v.paint ?? 0}, ${v.lane}, ${f3(v.at)}),`).join('\n')}
    };
    public const float POLICE_FLASH = ${f3(POLICE_FLASH)};
    static Vector2 At(Lane l, float a) { float r = l.R * (1 + l.Wob * Mathf.Sin(3 * a)); return new Vector2(Mathf.Cos(a) * r, Mathf.Sin(a) * r); }
    /** Where car v is at time t (seconds), in Unity's space (glTFast's flip applied), and how it is turned. */
    public static void Pose(Car v, float t, out Vector3 position, out Quaternion rotation) {
      var l = LANES[v.Lane];
      float a = v.At + l.Dir * l.Speed * t / l.R;
      Vector2 p = At(l, a), n = At(l, a + 0.02f * l.Dir);
      float y = l.Y + 0.35f * Mathf.Sin(t * 1.3f + v.At * 5);
      float yaw = Mathf.Atan2(n.x - p.x, n.y - p.y) * Mathf.Rad2Deg, bank = -l.Dir * 9;
      position = new Vector3(-p.x, y, p.y);
      rotation = Quaternion.Euler(0, -yaw, -bank);
    }
    /** Whether a police car's red light (else its blue one) is on at time t. */
    public static bool PoliceRed(float t, Car v) => ((int)Mathf.Floor(t * POLICE_FLASH * 2 + v.At * 3)) % 2 == 0;
  }
}
`);
// (the example in LEEME.md, as a file)
const leeme = readFileSync(join(ROOT, 'tools/quest/LEEME-bundle.md'), 'utf8'), example = /```csharp\n([\s\S]*?)```/.exec(leeme);
if (example) write('CSharp/Examples/FlyingTraffic.cs', `// The example of LEEME.md: the cyberpunk city's flying cars (not tried in Unity).\n${example[1]}`);
console.log('✔ C#: the rules (hand port + RulesData, TextsData, UiData), the looks (Neighbourhoods, Traffic), an example');

// --- the game's sources (reference: how it all is built and played) ------------------------------------------
const SOURCES = ['src/world', 'src/game', 'src/geo.js', 'src/rng.js', 'src/actors/player.js', 'src/actors/monsters.js', 'src/actors/candy.js', 'src/actors/costumes.js', 'src/actors/effects.js', 'src/poses.js', 'src/textures.js'];
for (const s of SOURCES) cpSync(join(ROOT, s), join(BASE, 'Reference', s), { recursive: true });
