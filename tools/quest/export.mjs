// npm run quest -- <Unity project folder> [--rules]
// Brings the game into its Unity project for Meta Quest (it lives in its own repository,
// trick-or-treat-rush-quest). Under <project> it writes
//   Assets/TrickOrTreat/Scripts/Rules/Generated/RulesData.cs   every rule number and the village plan, as C#
//   Assets/TrickOrTreat/Scripts/Rules/Generated/TextsData.cs   the game's texts in its four languages
//   Assets/TrickOrTreat/Scripts/Rules/Generated/UiData.cs      the panels' layout (the Spectacles Lens's, drawn in ui.glb)
//   tools/check/golden/*.trace.gz                               reference rounds played by this game's authority
//                                                               (tools/quest/trace.mjs), which the Quest's C# port
//                                                               must play line for line (dotnet run in tools/check)
//   Assets/TrickOrTreat/Resources/Models/*.glb                  the village, ghost, creatures, pickups, effects and the
//                                                               menus' plates: the Spectacles export's (npm run lens),
//                                                               imported by glTFast
//   Assets/TrickOrTreat/Resources/Audio/*                        the sounds and music (WAV) and the avatar's cries
//   Assets/TrickOrTreat/Resources/Fonts/*.ttf                    the game's two fonts (OFL)
//   Assets/TrickOrTreat/Animation/TrickOrTreatMoves.fbx          the moves as a Humanoid FBX (Blender, clips-fbx.mjs)
// `--rules`: only the C# and the reference rounds (seconds); the assets need Chromium and Blender (minutes).
// Generated files say so at the top; edit the game here, never there, and run this again.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { gzipSync } from 'node:zlib';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildClipsFbx } from './clips-fbx.mjs';
import { rulesCs, uiCs } from './rules-cs.mjs';
import { textsCs } from './texts-cs.mjs';
import { SCENARIOS, runTrace } from './trace.mjs';

const project = process.argv[2] && resolve(process.argv[2]);
if (!project || !existsSync(join(project, 'Assets'))) {
  console.error('usage: npm run quest -- <Unity project folder (the one with Assets/)>');
  process.exit(1);
}
const write = (rel, data) => { const f = join(project, rel); mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, data); };
const HEADER = (from) => `// Generated by tools/quest/export.mjs from trick-or-treat-rush/${from}. Do not edit: change the game and export again.\n`;

// --- the rules' data, as C# -------------------------------------------------------------------------
write('Assets/TrickOrTreat/Scripts/Rules/Generated/RulesData.cs', rulesCs(HEADER('src/game/config.js and src/world/layout.js')));
write('Assets/TrickOrTreat/Scripts/Rules/Generated/TextsData.cs', textsCs(HEADER('src/ui/i18n.js')));
write('Assets/TrickOrTreat/Scripts/Rules/Generated/UiData.cs', uiCs(HEADER('src/dev/lens-ui.js')));
console.log('✔ rules data: config, layout (RulesData.cs), texts (TextsData.cs), panels (UiData.cs)');

// --- reference rounds ----------------------------------------------------------------------------------
const golden = join(project, 'tools/check/golden');
if (existsSync(golden)) for (const f of readdirSync(golden)) if (f.endsWith('.trace.gz')) rmSync(join(golden, f));
let lines = 0;
for (const s of SCENARIOS) {
  const t = runTrace(s);
  lines += t.length;
  write(`tools/check/golden/${s.name}.trace.gz`, gzipSync(`${JSON.stringify(s)}\n${t.join('\n')}\n`, { level: 9 }));
}
console.log(`✔ reference rounds: ${SCENARIOS.length} (${lines} lines) in tools/check/golden`);

if (process.argv.includes('--rules')) process.exit(0);

// --- the assets ----------------------------------------------------------------------------------------
// The models, sounds and fonts the Spectacles Lens gets (its exporter, into a scratch project), then copied in.
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const scratch = mkdtempSync(join(tmpdir(), 'quest-assets-'));
mkdirSync(join(scratch, 'Assets'));
const lens = spawnSync('node', [join(ROOT, 'tools/lens-studio/export.mjs'), scratch, '--only=village,ghost,creatures,pickups,fx,ui,sounds'], { cwd: ROOT, stdio: 'inherit' });
if (lens.status !== 0) throw new Error('the Spectacles export failed');
const res = 'Assets/TrickOrTreat/Resources';
const copyAll = (from, to, keep, rename = (f) => f) => {
  let n = 0;
  for (const f of readdirSync(from)) {
    if (!keep(f)) continue;
    mkdirSync(join(project, to), { recursive: true });
    copyFileSync(join(from, f), join(project, to, rename(f)));
    n++;
  }
  return n;
};
const MODELS = /^(village|ghost|pickups|fx|ui|creature-[a-z]+)\.glb$/;
const m = copyAll(join(scratch, 'Assets/Models'), `${res}/Models`, (f) => MODELS.test(f));
const a = copyAll(join(scratch, 'Assets/Audio'), `${res}/Audio`, (f) => f.endsWith('.wav'));
const f = copyAll(join(scratch, 'Assets/Fonts'), `${res}/Fonts`, (x) => x.endsWith('.ttf'));
// The avatar's cries: the phone game's (npm run voices, from the Lens repo's WAVs; Lenslist's permission).
const v = copyAll(join(ROOT, 'public/assets/voice'), `${res}/Audio`, (x) => x.endsWith('.mp3'), (x) => `voice-${x}`);
rmSync(scratch, { recursive: true, force: true });
console.log(`✔ assets: ${m} models, ${a} sounds, ${v} cries, ${f} fonts in ${res}`);
console.log(buildClipsFbx(join(project, 'Assets/TrickOrTreat/Animation/TrickOrTreatMoves.fbx')).split('\n').pop());
