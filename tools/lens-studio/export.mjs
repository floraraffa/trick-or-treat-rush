// npm run lens -- <Lens Studio project folder> [--rules]
// Brings the game into its Lens Studio project for Spectacles (the Lens Studio 5.15 project lives in its
// own repository): under <project>/Assets it writes
//   Models/*.glb, Audio/*.wav, Scripts/Generated/clips.ts   from dev/lens-export.html, run in headless Chromium
//   Fonts/*.ttf                                             the game's two fonts (woff2 → TrueType, Python fontTools)
//   Scripts/Generated/*.ts                                  the shared rules, converted to TypeScript modules:
//     the same authority, levels, village plan, collisions, movement, texts and creature animation as the Lens.
// Generated files say so at the top; edit the game here, never there, and run this again.
// URL=http://localhost:3100/ uses a running dev server; otherwise one is started for the export.
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launch } from '../../tests/browser.mjs';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const project = process.argv[2] && resolve(process.argv[2]);
if (!project || !existsSync(join(project, 'Assets'))) {
  console.error('usage: npm run lens -- <Lens Studio project folder (the one with Assets/)>');
  process.exit(1);
}
const assets = join(project, 'Assets');
const write = (rel, data) => { const f = join(assets, rel); mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, data); };
const HEADER = (from) => `// Generated by tools/lens-studio/export.mjs from trick-or-treat-rush/${from}. Do not edit: change the game and export again.\n// @ts-nocheck\n`;

// --- the shared rules, as TypeScript ------------------------------------------------------------
const MODULES = {
  rng: 'src/rng.js', config: 'src/game/config.js', layout: 'src/world/layout.js', collide: 'src/world/collide.js',
  authority: 'src/game/authority.js', view: 'src/game/view.js', player: 'src/actors/player.js', i18n: 'src/ui/i18n.js',
  lensUi: 'src/dev/lens-ui.js', // (the Lens's panels: the same boxes the export draws)
};
const byFile = Object.fromEntries(Object.entries(MODULES).map(([name, file]) => [file.split('/').pop(), name]));
function convert(name, file) {
  let s = readFileSync(join(ROOT, file), 'utf8');
  s = s.replace(/from '([^']+)'/g, (m, path) => {
    const base = path.split('/').pop();
    if (!byFile[base]) throw new Error(`${file}: imports ${path}, which is not exported to Lens Studio`);
    return `from './${byFile[base]}'`;
  });
  s = s.replace(/performance\.now\(\)/g, '(getTime() * 1000)'); // Lens Studio's clock
  if (name === 'i18n') {
    s = s.replace("(navigator.language || 'en')", "(lensLanguage() || 'en')");
    s = s.replace(' document.documentElement.lang = lang;', '');
    s += "\n/** The device's language in Lens Studio (en, es...), when it says. */\nfunction lensLanguage() { try { return String(global.localizationSystem.getLanguage()); } catch (e) { return ''; } }\n";
  }
  for (const bad of ['document.', 'window.', 'navigator.', 'localStorage', 'import.meta']) if (s.includes(bad)) throw new Error(`${file}: uses ${bad}, which Lens Studio has not`);
  return HEADER(file) + s;
}
/** A Lens Studio .meta for a new TypeScript file (Lens Studio keeps it from then on). */
const scriptMeta = () => {
  const [a, b, c, d] = Array.from({ length: 4 }, () => randomUUID());
  return `- !<AssetImportMetadata/${a}>\n  ImportedAssetIds:\n    TypeScriptAsset: !<reference> ${b}\n  ImporterName: TypeScriptAssetImporter\n  PrimaryAsset: !<reference> ${b}\n  PackageType: NotAPackage\n  LegacyPackagePolicy: ~\n  ExtraData:\n    {}\n  AssetDataMap:\n    TypeScriptAsset: !<own> ${c}\n  DependentFiles:\n    []\n  ImporterSettings: !<AssetImporterSettings>\n    {}\n  CompressionSettings: !<own> 00000000-0000-0000-0000-000000000000\n` +
    `- !<TypeScriptAssetData/${c}>\n  SvgIcon: ""\n  SetupScript:\n    code: ""\n  Description: ""\n  VersionMajor: 0\n  VersionMinor: 0\n  VersionPatch: 0\n  ComponentUid: ${d}\n  ExportUid: 00000000-0000-0000-0000-000000000000\n  PackagePolicy: CanBeUnpacked\n  ScriptInputsHidden:\n    {}\n  ScriptTypesHidden:\n    {}\n  ReadMe: !<reference> 00000000-0000-0000-0000-000000000000\n  DeclarationFile: !<reference> 00000000-0000-0000-0000-000000000000\n  Tags:\n    []\n  Attachments:\n    []\n  DefaultScriptInputs:\n    -\n      {}\n  ScriptTypes:\n    -\n      {}\n  InputLines:\n    []\n`;
};
const writeScript = (rel, text) => { write(rel, text); if (!existsSync(join(assets, `${rel}.meta`))) write(`${rel}.meta`, scriptMeta()); };
for (const [name, file] of Object.entries(MODULES)) writeScript(`Scripts/Generated/${name}.ts`, convert(name, file));
// The creatures (their names, in the game's order) and their walk (animateCreature and the angle it hangs
// the arms at), cut out of creatures.js.
{
  const src = readFileSync(join(ROOT, 'src/actors/creatures.js'), 'utf8');
  const names = src.match(/export const CREATURES = [^\n]+\n/)[0];
  const arm = src.match(/const ARM_DOWN = [^\n]+\n/)[0];
  const fn = src.slice(src.indexOf('/**\n * Moves a creature\'s parts.'));
  writeScript('Scripts/Generated/creatureAnim.ts', HEADER('src/actors/creatures.js') + names + arm + '\n' + fn);
}
console.log('✔ rules: ' + Object.keys(MODULES).join(', ') + ', creatureAnim');

// --- fonts ----------------------------------------------------------------------------------------
for (const [font, out] of [['griffy', 'Griffy'], ['mystery-quest', 'MysteryQuest']]) {
  const src = join(ROOT, `node_modules/@fontsource/${font}/files/${font}-latin-400-normal.woff2`), dst = join(assets, `Fonts/${out}.ttf`);
  mkdirSync(dirname(dst), { recursive: true });
  const r = spawnSync('python3', ['-c', 'import sys\nfrom fontTools.ttLib import TTFont\nf = TTFont(sys.argv[1]); f.flavor = None; f.save(sys.argv[2])', src, dst], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`fonts: ${r.stderr || r.error} (pip install fonttools brotli)`);
}
console.log('✔ fonts: Griffy, MysteryQuest (OFL)');

// --- models, clips, sounds (in the browser) -------------------------------------------------------

/**
 * A GLB's images re-encoded to fit the Lens's budget: opaque ones (photos, normal maps) as mozjpeg, those with
 * transparency (the panels' plates, glows) as palette PNG when that is smaller; the binary laid out again.
 */
async function squeezeGlb(buf) {
  const jsonLen = buf.readUInt32LE(12), json = JSON.parse(buf.subarray(20, 20 + jsonLen).toString());
  if (!json.images?.length) return buf;
  const bin = buf.subarray(20 + jsonLen + 8, 20 + jsonLen + 8 + buf.readUInt32LE(20 + jsonLen));
  const views = json.bufferViews.map((v) => bin.subarray(v.byteOffset ?? 0, (v.byteOffset ?? 0) + v.byteLength));
  const normals = new Set((json.materials ?? []).map((m) => m.normalTexture?.index).filter((i) => i !== undefined).map((t) => json.textures[t].source));
  for (const [i, img] of json.images.entries()) {
    const src = views[img.bufferView], { isOpaque } = await sharp(src).stats();
    let out = null, type = img.mimeType;
    if (isOpaque) { out = await sharp(src).jpeg({ quality: normals.has(i) ? 86 : 82, mozjpeg: true }).toBuffer(); type = 'image/jpeg'; }
    else if (img.mimeType === 'image/png') out = await sharp(src).png({ palette: true, quality: 92, effort: 10, dither: 0.6 }).toBuffer();
    if (out && out.length < src.length) { views[img.bufferView] = out; img.mimeType = type; }
  }
  let offset = 0;
  views.forEach((v, i) => { json.bufferViews[i].byteOffset = offset; json.bufferViews[i].byteLength = v.length; offset += Math.ceil(v.length / 4) * 4; });
  const out = Buffer.alloc(offset);
  views.forEach((v, i) => v.copy(out, json.bufferViews[i].byteOffset));
  json.buffers[0].byteLength = offset;
  let text = JSON.stringify(json);
  while (text.length % 4) text += ' ';
  const head = Buffer.alloc(20), mid = Buffer.alloc(8);
  head.writeUInt32LE(0x46546c67, 0); head.writeUInt32LE(2, 4); head.writeUInt32LE(28 + text.length + offset, 8);
  head.writeUInt32LE(text.length, 12); head.writeUInt32LE(0x4e4f534a, 16);
  mid.writeUInt32LE(offset, 0); mid.writeUInt32LE(0x004e4942, 4);
  return Buffer.concat([head, Buffer.from(text), mid, out]);
}
if (process.argv.includes('--rules')) process.exit(0); // (`--rules`: only the scripts and fonts above, in seconds)
let server = null, url = process.env.URL;
if (!url) {
  const port = 3800 + Math.floor(Math.random() * 400);
  server = spawn('npx', ['vite', '--port', String(port), '--strictPort'], { cwd: ROOT, stdio: 'ignore' });
  url = `http://localhost:${port}/`;
  await new Promise((r) => setTimeout(r, 4000));
}
const browser = await launch();
try {
  // (`--only=fx,sounds`: just those steps: village, ghost, creatures, pickups, fx, ui, clips, sounds)
  const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7).split(',') ?? null;
  // The panels' plates, drawn by the web game's own styles and photographed on a clear background (4 pixels
  // a CSS pixel: 40 a centimetre; the big panels at half that).
  let uiImages = null;
  if (!only || only.includes('ui')) {
    const shot = await browser.newPage({ viewport: { width: 2620, height: 1400 }, deviceScaleFactor: 4 });
    await shot.goto(`${url}dev/lens-ui.html`);
    await shot.waitForFunction(() => window.__ready, null, { timeout: 120000 });
    uiImages = {};
    for (const p of await shot.evaluate(() => window.__plates)) {
      let png = await (await shot.$(`[id="plate-${p.key}"]`)).screenshot({ omitBackground: true });
      if (p.kind === 'tome') { const m = await sharp(png).metadata(); png = await sharp(png).resize(Math.round(m.width / 2)).png().toBuffer(); }
      uiImages[p.key] = `data:image/png;base64,${png.toString('base64')}`;
    }
    await shot.close();
  }
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.error('page error:', e.message));
  await page.goto(`${url}dev/lens-export.html`);
  await page.waitForFunction(() => window.__ready, null, { timeout: 180000 });
  const { files, report, errors } = await page.evaluate(([o, uiImages]) => window.__export(o, { uiImages }), [only, uiImages]);
  if (errors.length) throw new Error(errors.join('\n'));
  for (const [rel, b64] of Object.entries(files)) {
    const data = Buffer.from(b64, 'base64');
    if (rel.endsWith('.ts')) writeScript(rel, data);
    else if (rel.endsWith('.glb')) write(rel, await squeezeGlb(data));
    else write(rel, data);
  }
  for (const [k, v] of Object.entries(report)) console.log(`✔ ${k}: ${typeof v === 'object' ? JSON.stringify(v) : v}`);
} finally {
  await browser.close();
  server?.kill();
}
